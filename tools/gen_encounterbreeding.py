#!/usr/bin/env python3
"""Generate include/Legality/Encounters/EncounterBreedingTable.h + src/Legality/Encounters/EncounterBreedingTable.cpp
from PKHeX PKHeX.Core/Legality/Breeding.cs: the species lists the encounter engine's egg templates read.

  - IsAbleToHatchFromEgg: the species that can never hatch from an egg;
  - IsSplitBreedNotBabySpecies4: the parents whose egg can be a different baby (incense);
  - IsBreedableForm: the species whose non-zero forms never hatch (a form-specific entry keeps its form).

Regenerate with:  python tools/gen_encounterbreeding.py
Reads PKHeX through tools/pkhex_source.py (PKHEX_LOCAL points it at a checkout).
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_encounters import SPECIES, read_cs, strip_comments  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "include", "Legality", "Encounters", "EncounterBreedingTable.h")
OUT_CPP = os.path.join(ROOT, "src", "Legality", "Encounters", "EncounterBreedingTable.cpp")
SOURCE = "Legality/Breeding.cs"


def switch_body(text, method):
    match = re.search(r"\b" + method + r"\([^)]*\)\s*=>\s*species\s+switch\s*\{", text)
    if not match:
        raise SystemExit("%s not found in %s" % (method, SOURCE))
    depth, index = 1, match.end()
    while depth:
        if text[index] == "{":
            depth += 1
        elif text[index] == "}":
            depth -= 1
        index += 1
    return text[match.end():index - 1]


def arms(body, wanted):
    """(species ids, form or None) of each `(int)A or (int)B [when form == n] => wanted` arm."""
    out = []
    for arm in body.split(","):
        if "=>" not in arm:
            continue
        left, right = arm.split("=>")
        if right.strip() != wanted:
            continue
        form = None
        form_match = re.search(r"when\s+form\s*==\s*(\d+)", left)
        if form_match:
            form = int(form_match.group(1))
            left = left[:form_match.start()]
        names = re.findall(r"\(int\)\s*([^\W\d]\w*)", left)
        if not names:
            continue
        out.append(([SPECIES[name] for name in names], form))
    return out


def main():
    text = strip_comments(read_cs(SOURCE))
    unhatchable = sorted(species for ids, _ in arms(switch_body(text, "IsAbleToHatchFromEgg"), "false") for species in ids)
    split = sorted(species for ids, _ in arms(switch_body(text, "IsSplitBreedNotBabySpecies4"), "true") for species in ids)
    form_rows = []
    for ids, form in arms(switch_body(text, "IsBreedableForm"), "false"):
        for species in ids:
            form_rows.append((species, 0xFF if form is None else form))
    form_rows.sort()

    def wrap(values):
        lines, line = [], []
        for value in values:
            line.append(str(value))
            if len(line) == 16:
                lines.append("        " + ", ".join(line) + ",")
                line = []
        if line:
            lines.append("        " + ", ".join(line) + ",")
        return "\n".join(lines)

    header = """/**
 * Auto-generated by tools/gen_encounterbreeding.py from PKHeX PKHeX.Core/Legality/Breeding.cs.
 * DO NOT EDIT BY HAND -- rerun the generator instead.
 */
#ifndef LEGALITY_ENCOUNTERS_ENCOUNTERBREEDINGTABLE_H
#define LEGALITY_ENCOUNTERS_ENCOUNTERBREEDINGTABLE_H

#include <cstdint>
#include <span>

namespace Legality
{
    namespace Encounters
    {
        /// A species whose forms other than `formId` never hatch (0xFF: no form but 0 hatches).
        struct UnbreedableForm
        {
            uint16_t speciesId;
            uint8_t formId;
        };

        /// PKHeX Breeding.IsAbleToHatchFromEgg's false arms, ascending.
        std::span<const uint16_t> getUnhatchableSpecies() noexcept;
        /// PKHeX Breeding.IsSplitBreedNotBabySpecies4's true arms, ascending.
        std::span<const uint16_t> getSplitBreedSpecies4() noexcept;
        /// PKHeX Breeding.IsBreedableForm's false arms.
        std::span<const UnbreedableForm> getUnbreedableForms() noexcept;
    }
}

#endif
"""
    source = """// Auto-generated by tools/gen_encounterbreeding.py. DO NOT EDIT BY HAND.
#include "Legality/Encounters/EncounterBreedingTable.h"

namespace Legality
{
    namespace Encounters
    {
        namespace
        {
            // clang-format off
            constexpr uint16_t UNHATCHABLE_SPECIES[] = {
%s
            };
            constexpr uint16_t SPLIT_BREED_SPECIES4[] = {
%s
            };
            constexpr UnbreedableForm UNBREEDABLE_FORMS[] = {
%s
            };
            // clang-format on
        }

        std::span<const uint16_t> getUnhatchableSpecies() noexcept
        {
            return UNHATCHABLE_SPECIES;
        }

        std::span<const uint16_t> getSplitBreedSpecies4() noexcept
        {
            return SPLIT_BREED_SPECIES4;
        }

        std::span<const UnbreedableForm> getUnbreedableForms() noexcept
        {
            return UNBREEDABLE_FORMS;
        }
    }
}
""" % (wrap(unhatchable).replace("        ", "                ", 1).replace("\n        ", "\n                "),
       wrap(split).replace("        ", "                ", 1).replace("\n        ", "\n                "),
       "\n".join("                {%d, %d}," % row for row in form_rows))
    with open(OUT_H, "w", newline="\n") as handle:
        handle.write(header)
    with open(OUT_CPP, "w", newline="\n") as handle:
        handle.write(source)
    print("unhatchable %d, split-breed %d, unbreedable forms %d" % (len(unhatchable), len(split), len(form_rows)))


if __name__ == "__main__":
    main()
