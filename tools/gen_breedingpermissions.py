#!/usr/bin/env python3
"""Generate include/Legality/Verifiers/BreedingPermissionTable.h + src/Legality/Verifiers/BreedingPermissionTable.cpp
from PKHeX's per-species breeding permission tables, for the ball and ability legality checks:

  - BallContext6.Permit, BallContext7.Permit, BallContextHOME.Permit: one byte per species, one bit
    per ball family an egg of that species may inherit (PKHeX BallVerifier's egg ball inheritance);
  - AbilityBreedLegality.BanHidden5: one bit per species that cannot be bred with its Hidden Ability
    in Generation 5 (PKHeX EncounterEgg5.Ability).

The bit meanings are the BallType enum each BallContext file declares; the C++ side names them in
BallVerifier.cpp. Bytes are copied verbatim, in species order.

Regenerate with:  python tools/gen_breedingpermissions.py
Pulls the PKHeX sources it reads from GitHub on demand (tools/pkhex_source.py); PKHEX_LOCAL points it at
a checkout instead.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkhex_source import pkhex_path  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "include", "Legality", "Verifiers", "BreedingPermissionTable.h")
OUT_CPP = os.path.join(ROOT, "src", "Legality", "Verifiers", "BreedingPermissionTable.cpp")

# (C++ constant, PKHeX source file under PKHeX.Core, span name, what it holds)
TABLES = [
    ("BALL_PERMIT_GENERATION_6", "Legality/Verifiers/Ball/BallContext6.cs", "Permit", "Ball families an egg may inherit in X/Y and Omega Ruby/Alpha Sapphire (PKHeX BallContext6.Permit)."),
    ("BALL_PERMIT_GENERATION_7", "Legality/Verifiers/Ball/BallContext7.cs", "Permit", "Ball families an egg may inherit in Sun/Moon and Ultra Sun/Ultra Moon (PKHeX BallContext7.Permit)."),
    ("BALL_PERMIT_HOME", "Legality/Verifiers/Ball/BallContextHOME.cs", "Permit", "Ball families an egg may inherit in the games HOME connects (PKHeX BallContextHOME.Permit)."),
    ("HIDDEN_ABILITY_BAN_GENERATION_5", "Legality/Verifiers/Ability/AbilityBreedLegality.cs", "BanHidden5", "One bit per species (bit `species & 7` of byte `species >> 3`) that cannot be bred with its Hidden Ability in Black/White and Black 2/White 2 (PKHeX AbilityBreedLegality.BanHidden5)."),
]


def read_span(relpath, name):
    with open(pkhex_path(relpath), encoding="utf-8") as handle:
        text = handle.read()
    match = re.search(r"ReadOnlySpan<byte>\s+" + re.escape(name) + r"\s*=>\s*\[(.*?)\];", text, re.S)
    if not match:
        raise SystemExit(f"{relpath}: span {name} not found")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    values = [int(token, 16) for token in re.findall(r"0x[0-9A-Fa-f]{2}", body)]
    if not values:
        raise SystemExit(f"{relpath}: span {name} is empty")
    return values


def format_bytes(values):
    lines = []
    for start in range(0, len(values), 20):
        chunk = ", ".join(f"0x{value:02X}" for value in values[start:start + 20])
        lines.append(f"        {chunk},")
    return "\n".join(lines)


def main():
    spans = [(constant, read_span(relpath, name), doc) for constant, relpath, name, doc in TABLES]

    header = [
        "/**",
        " * Auto-generated by tools/gen_breedingpermissions.py from PKHeX's BallContext6/7/HOME and",
        " * AbilityBreedLegality tables. DO NOT EDIT BY HAND -- rerun the generator instead.",
        " *",
        " * Per-species breeding permissions the ball and ability verifiers read. A species past the end",
        " * of a table has no entry, which each reader treats the way PKHeX does.",
        " */",
        "#ifndef LEGALITY_VERIFIERS_BREEDINGPERMISSIONTABLE_H",
        "#define LEGALITY_VERIFIERS_BREEDINGPERMISSIONTABLE_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace Legality",
        "{",
    ]
    for constant, values, doc in spans:
        header.append(f"    /// {doc}")
        header.append(f"    constexpr size_t {constant}_LENGTH = {len(values)};")
        header.append(f"    extern const uint8_t {constant}[{constant}_LENGTH];")
        header.append("")
    header[-1:] = ["}", "", "#endif", ""]

    source = [
        "// Auto-generated by tools/gen_breedingpermissions.py. DO NOT EDIT BY HAND -- rerun the generator instead.",
        "#include \"Legality/Verifiers/BreedingPermissionTable.h\"",
        "",
        "namespace Legality",
        "{",
    ]
    for constant, values, _ in spans:
        source.append(f"    const uint8_t {constant}[{constant}_LENGTH] = {{")
        source.append(format_bytes(values))
        source.append("    };")
        source.append("")
    source[-1:] = ["}", ""]

    with open(OUT_H, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(header))
    with open(OUT_CPP, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(source))
    print(f"wrote {OUT_H} and {OUT_CPP}: " + ", ".join(f"{constant} {len(values)}" for constant, values, _ in spans))


if __name__ == "__main__":
    main()
