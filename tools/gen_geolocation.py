#!/usr/bin/env python3
"""Generate include/Legality/Verifiers/GeolocationTable.h from PKHeX's 3DS country and region lists, for
the legality checker's geolocation check (PKHeX GeoLocation.GetIsCountryRegionExist, read by
HistoryVerifier through IGeoTrack.GetValidity).

PKHeX reads Resources/text/locale3DS/countries.txt for the country ids and subregions/sr_NNN.txt for
the region ids of country NNN; a (country, region) pair exists when the region's line is in its
country's file. Only the ids matter here, so the table is one bitset of region ids per country id.

Regenerate with:  python tools/gen_geolocation.py
Pulls the PKHeX sources it reads from GitHub on demand (tools/pkhex_source.py); PKHEX_LOCAL points it at
a checkout instead.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkhex_source import pkhex_path  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "include", "Legality", "Verifiers", "GeolocationTable.h")
LOCALE = "Resources/text/locale3DS/"


def line_ids(relpath):
    with open(pkhex_path(relpath), encoding="utf-8-sig") as handle:
        return [int(line.split("\t")[0]) for line in handle if line.strip()]


def main():
    countries = line_ids(LOCALE + "countries.txt")
    country_count = max(countries) + 1
    regions_by_country = {}
    for country in countries:
        if country == 0:
            continue
        regions_by_country[country] = line_ids(LOCALE + f"subregions/sr_{country:03d}.txt")
    region_limit = max(max(regions) for regions in regions_by_country.values()) + 1
    bitset_bytes = (region_limit + 7) // 8

    rows = []
    for country in range(country_count):
        bitset = [0] * bitset_bytes
        for region in regions_by_country.get(country, []):
            bitset[region >> 3] |= 1 << (region & 7)
        rows.append("        {" + ", ".join(f"0x{value:02X}" for value in bitset) + f"}}, // {country:03d}")

    text = f'''/**
 * Auto-generated by tools/gen_geolocation.py from PKHeX's 3DS country and region lists
 * (PKHeX.Core/Resources/text/locale3DS). DO NOT EDIT BY HAND -- rerun the generator instead.
 *
 * Which (country, region) pairs a 3DS geolocation can hold (PKHeX GeoLocation.GetIsCountryRegionExist).
 * Row = country id; bit N of a row = region N exists in that country. A country with no region file
 * (0, "no country") has an empty row.
 */
#ifndef LEGALITY_VERIFIERS_GEOLOCATIONTABLE_H
#define LEGALITY_VERIFIERS_GEOLOCATIONTABLE_H

#include <cstdint>

namespace Legality
{{
    inline constexpr int GEOLOCATION_COUNTRY_COUNT = {country_count};
    inline constexpr int GEOLOCATION_REGION_BITSET_SIZE = {bitset_bytes};

    // clang-format off
    inline constexpr uint8_t GEOLOCATION_REGIONS_BY_COUNTRY[GEOLOCATION_COUNTRY_COUNT][GEOLOCATION_REGION_BITSET_SIZE] = {{
{chr(10).join(rows)}
    }};
    // clang-format on

    /// PKHeX GeoLocation.GetIsCountryRegionExist.
    inline bool isGeolocationRegionInCountry(uint8_t country, uint8_t region)
    {{
        if (country >= GEOLOCATION_COUNTRY_COUNT || (region >> 3) >= GEOLOCATION_REGION_BITSET_SIZE)
        {{
            return false;
        }}
        return (GEOLOCATION_REGIONS_BY_COUNTRY[country][region >> 3] & (1 << (region & 7))) != 0;
    }}
}}

#endif
'''
    with open(OUT_H, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {os.path.relpath(OUT_H, ROOT)}: {country_count} countries, regions below {region_limit}")


if __name__ == "__main__":
    main()
