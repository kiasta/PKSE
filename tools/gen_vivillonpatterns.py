#!/usr/bin/env python3
"""Generate include/Legality/Verifiers/VivillonPatternTable.h + src/Legality/Verifiers/VivillonPatternTable.cpp
from PKHeX's Vivillon3DS tables, for the form legality check (PKHeX FormVerifier): which 3DS console
regions offer each wild Vivillon pattern, and which pattern a 3DS country/region pair produces.

    VivillonRegionTable  one Region3DSFlags byte per pattern 0-17
    SameCountry          one byte per country: its pattern, or 0 when it depends on the region
    DiffCountryRegion    sorted (country << 8 | region) keys for the countries that depend on it
    DiffForm             the pattern for each of those keys

Regenerate with:  python tools/gen_vivillonpatterns.py
Pulls the PKHeX sources it reads from GitHub on demand (tools/pkhex_source.py); PKHEX_LOCAL points it at
a checkout instead.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkhex_source import pkhex_path  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = "Legality/Restrictions/Locale/Vivillon3DS.cs"
OUT_H = os.path.join(ROOT, "include", "Legality", "Verifiers", "VivillonPatternTable.h")
OUT_CPP = os.path.join(ROOT, "src", "Legality", "Verifiers", "VivillonPatternTable.cpp")


def span_body(text, element_type, name):
    match = re.search(r"ReadOnlySpan<" + element_type + r">\s+" + re.escape(name) + r"\s*=>\s*\[(.*?)\];", text, re.S)
    if not match:
        raise SystemExit(f"{SOURCE}: span {name} not found")
    return re.sub(r"//[^\n]*", "", match.group(1))


def region_flags(text):
    enum_body = re.search(r"enum Region3DSFlags[^{]*\{(.*?)\}", text, re.S).group(1)
    flags = {name: (1 << int(shift)) if shift else 0 for name, shift in re.findall(r"(\w+)\s*=\s*(?:1\s*<<\s*(\d+)|0)", enum_body)}
    body = re.sub(r"/\*.*?\*/", "", span_body(text, "Region3DSFlags", "VivillonRegionTable"), flags=re.S)
    values = []
    for entry in body.split(","):
        names = [token.strip() for token in entry.split("|") if token.strip()]
        if names:
            value = 0
            for flag_name in names:
                value |= flags[flag_name]
            values.append(value)
    return values


def format_values(values, width, per_line):
    lines = []
    for start in range(0, len(values), per_line):
        chunk = ", ".join(f"0x{value:0{width}X}" for value in values[start:start + per_line])
        lines.append(f"        {chunk},")
    return "\n".join(lines)


def main():
    with open(pkhex_path(SOURCE), encoding="utf-8") as handle:
        text = handle.read()
    max_wild = int(re.search(r"MaxWildFormID\s*=\s*(\d+)", text).group(1))
    region_table = region_flags(text)
    same_country = [0 if token == "XX" else int(token, 10) for token in re.findall(r"XX|\d+", span_body(text, "byte", "SameCountry"))]
    diff_keys = [int(token, 16) for token in re.findall(r"0x[0-9A-Fa-f]+", span_body(text, "ushort", "DiffCountryRegion"))]
    diff_forms = [int(token, 10) for token in re.findall(r"\d+", span_body(text, "byte", "DiffForm"))]
    if len(region_table) != max_wild + 1 or len(diff_keys) != len(diff_forms) or diff_keys != sorted(diff_keys):
        raise SystemExit("Vivillon3DS tables are not the expected shape")

    tables = [
        ("VIVILLON_PATTERN_REGIONS", "uint8_t", region_table, 2, "One bit per 3DS console region (bit = 1 << consoleRegion) that offers each wild pattern (PKHeX Vivillon3DS.VivillonRegionTable)."),
        ("VIVILLON_COUNTRY_PATTERN", "uint8_t", same_country, 2, "The pattern every region of a country produces, or 0 when it differs by region (PKHeX Vivillon3DS.SameCountry)."),
        ("VIVILLON_COUNTRY_REGION_KEYS", "uint16_t", diff_keys, 4, "Sorted `country << 8 | region` keys of the countries whose pattern differs by region (PKHeX Vivillon3DS.DiffCountryRegion)."),
        ("VIVILLON_COUNTRY_REGION_PATTERN", "uint8_t", diff_forms, 2, "The pattern for each key above (PKHeX Vivillon3DS.DiffForm)."),
    ]

    header = [
        "/**",
        " * Auto-generated by tools/gen_vivillonpatterns.py from PKHeX's Vivillon3DS tables.",
        " * DO NOT EDIT BY HAND -- rerun the generator instead.",
        " */",
        "#ifndef LEGALITY_VERIFIERS_VIVILLONPATTERNTABLE_H",
        "#define LEGALITY_VERIFIERS_VIVILLONPATTERNTABLE_H",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace Legality",
        "{",
        "    /// The highest wild Vivillon pattern; Fancy (18) and Poke Ball (19) are event-only (PKHeX Vivillon3DS.MaxWildFormID).",
        f"    constexpr uint8_t VIVILLON_MAX_WILD_FORM = {max_wild};",
        "",
    ]
    source = [
        "// Auto-generated by tools/gen_vivillonpatterns.py. DO NOT EDIT BY HAND -- rerun the generator instead.",
        "#include \"Legality/Verifiers/VivillonPatternTable.h\"",
        "",
        "namespace Legality",
        "{",
    ]
    for constant, element_type, values, width, doc in tables:
        header.append(f"    /// {doc}")
        header.append(f"    constexpr size_t {constant}_LENGTH = {len(values)};")
        header.append(f"    extern const {element_type} {constant}[{constant}_LENGTH];")
        header.append("")
        source.append(f"    const {element_type} {constant}[{constant}_LENGTH] = {{")
        source.append(format_values(values, width, 16))
        source.append("    };")
        source.append("")
    header[-1:] = ["}", "", "#endif", ""]
    source[-1:] = ["}", ""]

    with open(OUT_H, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(header))
    with open(OUT_CPP, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(source))
    print(f"wrote {OUT_H} and {OUT_CPP}: " + ", ".join(f"{constant} {len(values)}" for constant, _, values, _, _ in tables))


if __name__ == "__main__":
    main()
