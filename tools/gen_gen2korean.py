#!/usr/bin/env python3
"""Generate include/Utils/Gen2KoreanText.h from PKHeX's StringConverter2KOR tables.

Korean Gold/Silver store text in eleven 256-entry character tables selected by a prefix byte
(PKHeX StringConverter2KOR Table1..TableB). PKSE does not decode that text yet; what the legality
checker needs is the SET those tables cover, because a Game Boy name a Korean cartridge could not
have written is a finding (PKHeX StringConverter2KOR.GetIsKorean, used by NicknameVerifier and
TrainerNameVerifier).

Emitted as one sorted array of the distinct code points, for a binary search. Table0 is left out,
as PKHeX's IsKoreanChar leaves it out (none of its glyphs is reachable from the keyboard).

Regenerate:  python tools/gen_gen2korean.py
Pulls the PKHeX source from GitHub on demand (tools/pkhex_source.py); PKHEX_LOCAL uses a checkout.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkhex_source import pkhex_path, pkhex_ref  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "include", "Utils", "Gen2KoreanText.h")
SOURCE = "PKM/Strings/StringConverter2KOR.cs"
TABLE_NAMES = ["Table%X" % index for index in range(1, 12)]


def main():
    with open(pkhex_path(SOURCE), encoding="utf-8") as handle:
        source = handle.read()
    characters = set()
    for table_name in TABLE_NAMES:
        match = re.search(r"ReadOnlySpan<char> %s =>\s*\[(.*?)\];" % table_name, source, re.S)
        if match is None:
            raise SystemExit("table %s not found in %s" % (table_name, SOURCE))
        for literal in re.findall(r"'(\\.|[^'])'", match.group(1)):
            if literal.startswith("\\"):
                raise SystemExit("escaped character literal %r in %s" % (literal, table_name))
            characters.add(ord(literal))
    ordered = sorted(characters)

    parts = []
    parts.append("// AUTO-GENERATED by tools/gen_gen2korean.py from PKHeX %s. Do not edit.\n" % pkhex_ref())
    parts.append("// Source: PKHeX.Core/%s, Table1..TableB.\n" % SOURCE)
    parts.append("#ifndef UTILS_GEN2KOREANTEXT_H\n#define UTILS_GEN2KOREANTEXT_H\n\n")
    parts.append("#include <cstddef>\n#include <cstdint>\n\n")
    parts.append("namespace Utils\n{\n")
    parts.append("    /// Every character Korean Gold/Silver's text tables can store, sorted.\n")
    parts.append("    // clang-format off\n")
    parts.append("    inline constexpr char16_t GEN2_KOREAN_CHARACTERS[] = {\n")
    for index in range(0, len(ordered), 12):
        parts.append("        " + " ".join("0x%04X," % code for code in ordered[index:index + 12]) + "\n")
    parts.append("    };\n")
    parts.append("    // clang-format on\n\n")
    parts.append("    /// PKHeX StringConverter2KOR.IsKoreanChar.\n")
    parts.append("    inline bool isGen2KoreanCharacter(char16_t character) noexcept\n    {\n")
    parts.append("        constexpr size_t characterCount = sizeof(GEN2_KOREAN_CHARACTERS) / sizeof(GEN2_KOREAN_CHARACTERS[0]);\n")
    parts.append("        size_t lowIndex = 0;\n")
    parts.append("        size_t highIndex = characterCount;\n")
    parts.append("        while (lowIndex < highIndex)\n        {\n")
    parts.append("            const size_t middleIndex = (lowIndex + highIndex) / 2;\n")
    parts.append("            if (GEN2_KOREAN_CHARACTERS[middleIndex] < character)\n            {\n")
    parts.append("                lowIndex = middleIndex + 1;\n            }\n")
    parts.append("            else\n            {\n                highIndex = middleIndex;\n            }\n        }\n")
    parts.append("        return lowIndex < characterCount && GEN2_KOREAN_CHARACTERS[lowIndex] == character;\n    }\n")
    parts.append("}\n\n#endif\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(parts))
    print("Wrote", OUT, "with", len(ordered), "characters")


if __name__ == "__main__":
    main()
