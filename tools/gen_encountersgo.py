#!/usr/bin/env python3
"""Generate include/Legality/Encounters/EncounterDataGO.h + src/Legality/Encounters/EncounterDataGO.cpp:
PKHeX's Pokemon GO encounter templates (EncountersGO.SlotsGO_GG and SlotsGO), unmerged and in PKHeX's
own order, as the encounter engine's EncounterSlot7GO / EncounterSlot8GO.

SOURCES (PKHeX, via tools/pkhex_source.py; PKHEX_LOCAL points it at a checkout)
    Resources/legality/wild/encounter_go_lgpe.pkl    EncounterArea7g.GetArea (GO Park, Let's Go)
    Resources/legality/wild/encounter_go_home.pkl    EncounterArea8g.GetArea (GO to HOME)

Each area is a 4-byte header (u16 species, form, import format) and 12-byte slots: u16 start day,
u16 end day, shiny, gender, PogoType, PogoBallRestriction, PogoFlags, minimum level, minimum IV, and
one unused byte.

Regenerate:  python tools/gen_encountersgo.py
"""
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_encounters import WILD, _load, split_blobs_uint32  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "include", "Legality", "Encounters", "EncounterDataGO.h")
OUT_CPP = os.path.join(ROOT, "src", "Legality", "Encounters", "EncounterDataGO.cpp")

AREA_HEADER_SIZE = 4
SLOT_SIZE = 12
SHINY = ["Random", "Never", "Always", "AlwaysStar", "AlwaysSquare", "FixedValue"]
IMPORT_FORMAT = ["PK7", "PB7", "PK8", "PA8", "PK9"]
BALL_RESTRICTION = ["None", "StandardMaster", "Standard", "OnlyPoke", "OnlyPremier", "OnlyBeast", "OnlySafari"]
# PKHeX PogoType, by stored value
POGO_TYPE = {0: "None", 1: "Wild", 2: "Egg", 3: "Egg12km", 10: "Raid", 11: "RaidMythical", 12: "RaidUltraBeast", 13: "RaidShadow",
             14: "RaidShadowMythical", 15: "RaidShadowUltraBeast", 20: "FieldResearch", 21: "ResearchBreakthrough", 22: "SpecialResearch",
             23: "TimedResearch", 24: "CollectionChallenge", 25: "VivillonCollector", 26: "PartyPlay", 27: "StampRally", 28: "GOPass",
             29: "ReferralBonus", 40: "GBL", 41: "GBLMythical", 42: "GBLEvent", 50: "Shadow", 51: "ShadowMythical", 52: "ShadowUltraBeast",
             60: "MaxBattle", 61: "MaxBattleMythical", 62: "MaxBattleUltraBeast", 63: "MaxBattleGigantamax", 254: "PremierBallBug",
             255: "PremierBallBugMythical"}


def read_areas(file_name):
    areas = []
    for blob in split_blobs_uint32(_load(WILD(file_name))):
        species, form, import_format = struct.unpack_from("<HBB", blob, 0)
        body = blob[AREA_HEADER_SIZE:]
        slots = [struct.unpack_from("<HHBBBBBBB", body, offset) for offset in range(0, (len(body) // SLOT_SIZE) * SLOT_SIZE, SLOT_SIZE)]
        areas.append((species, form, import_format, slots))
    return areas


def emit(areas, name, slot_class, area_class, with_ball):
    slot_lines, area_lines = [], []
    for species, form, import_format, slots in areas:
        first_slot = len(slot_lines)
        for start, end, shiny, gender, pogo_type, ball, flags, level_min, minimum_iv in slots:
            arguments = [str(start), str(end), str(species), str(form), str(level_min), str(minimum_iv), "RNG::Shiny::" + SHINY[shiny], str(gender),
                         "PogoType::" + POGO_TYPE[pogo_type]]
            if with_ball:
                arguments += ["PogoBallRestriction::" + BALL_RESTRICTION[ball], "PogoImportFormat::" + IMPORT_FORMAT[import_format]]
            arguments.append(str(flags))
            slot_lines.append("                %s(%s)," % (slot_class, ", ".join(arguments)))
        area_lines.append("                %s{%d, %d, &SLOTS_%s[%d], %d}," % (area_class, species, form, name, first_slot, len(slot_lines) - first_slot))
    return ("            const %s SLOTS_%s[] = {\n%s\n            };\n" % (slot_class, name, "\n".join(slot_lines))
            + "            const %s AREAS_%s[] = {\n%s\n            };\n" % (area_class, name, "\n".join(area_lines)))


def main():
    lgpe = read_areas("encounter_go_lgpe.pkl")
    home = read_areas("encounter_go_home.pkl")
    blocks = emit(lgpe, "GO_LGPE", "EncounterSlot7GO", "EncounterArea7g", False) + emit(home, "GO_HOME", "EncounterSlot8GO", "EncounterArea8g", True)

    header = """/**
 * Auto-generated by tools/gen_encountersgo.py from PKHeX's Pokemon GO encounter data. DO NOT EDIT BY
 * HAND -- rerun the generator instead.
 *
 * PKHeX EncountersGO.SlotsGO_GG (GO Park) and SlotsGO (GO to HOME), in PKHeX's order.
 */
#ifndef LEGALITY_ENCOUNTERS_ENCOUNTERDATAGO_H
#define LEGALITY_ENCOUNTERS_ENCOUNTERDATAGO_H

#include <span>

#include "Legality/Encounters/EncounterSlot7GO.h"
#include "Legality/Encounters/EncounterSlot8GO.h"

namespace Legality
{
    namespace Encounters
    {
        std::span<const EncounterArea7g> getAreasGoLetsGo() noexcept;
        std::span<const EncounterArea8g> getAreasGoHome() noexcept;
    }
}

#endif
"""
    source = """// Auto-generated by tools/gen_encountersgo.py. DO NOT EDIT BY HAND.
#include "Legality/Encounters/EncounterDataGO.h"

namespace Legality
{
    namespace Encounters
    {
        namespace
        {
            // clang-format off
%s            // clang-format on
        }

        std::span<const EncounterArea7g> getAreasGoLetsGo() noexcept
        {
            return AREAS_GO_LGPE;
        }

        std::span<const EncounterArea8g> getAreasGoHome() noexcept
        {
            return AREAS_GO_HOME;
        }
    }
}
""" % blocks
    with open(OUT_H, "w", newline="\n") as handle:
        handle.write(header)
    with open(OUT_CPP, "w", newline="\n") as handle:
        handle.write(source)
    print("wrote %s (%d Let's Go areas, %d HOME areas)" % (os.path.relpath(OUT_CPP, ROOT), len(lgpe), len(home)))


if __name__ == "__main__":
    main()
